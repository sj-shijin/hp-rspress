#!/usr/bin/env python3
"""把官方 Mono GB v1.530 字体转换为按需加载的网页字体；仅更新网站资源。"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil

from fontTools import subset
from fontTools.ttLib import TTFont

VERSION = '1.530'
SOURCE = 'https://github.com/lxgw/LxgwWenkaiGB/releases/tag/v1.530'
FONTS = {
    'Regular': (400, '4baa9679b0aae3983a8b03c49f5cccce796b503b95e900120e8e6f3c07a6519c'),
    'Medium': (500, '34d96d3858ba2c89732e2517f08b236e56047171e82ba0e18f2db7e2921759bc'),
}


def unicode_ranges(points):
    """合并连续码点，供浏览器按 unicode-range 选择字体分片。"""
    runs = []
    for point in sorted(points):
        if runs and point == runs[-1][1] + 1:
            runs[-1][1] = point
        else:
            runs.append([point, point])
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in runs)


def prepare(source: Path, output: Path):
    # GB2312 的常用字符固定，不随知识库内容变化；其余字符保留在扩展分片中。
    common = set()
    for a in range(0xA1, 0xF8):
        for b in range(0xA1, 0xFF):
            text = bytes([a, b]).decode('gb2312', errors='ignore')
            common.update(map(ord, text))
    common.update(range(0x3000, 0x3100))
    common.update(range(0xFF00, 0xFFF0))
    output.mkdir(parents=True, exist_ok=True)
    styles = [f'/* LXGW WenKai Mono GB v{VERSION}; OFL-1.1; generated by scripts/prepare_fonts.py. */']
    report = {'family': 'LXGW WenKai Mono GB', 'version': VERSION, 'source': SOURCE,
              'source_commit': '603cad835e132872f26831e36b989c574f3d0a5a', 'fonts': []}
    for style, (weight, expected_hash) in FONTS.items():
        path = source / f'LXGWWenKaiMonoGB-{style}.ttf'
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if digest != expected_hash:
            raise ValueError(f'{path.name} 与已核验的官方 v{VERSION} 文件不一致')
        with TTFont(path) as original:
            points = set(original.getBestCmap())
        latin = {p for p in points if p < 0x2E80}
        groups = {'latin': latin, 'common': (points & common) - latin,
                  'extended': points - common - latin}
        for group, characters in groups.items():
            font = TTFont(path, recalcTimestamp=False)
            options = subset.Options()
            options.name_IDs = ['*']
            options.name_languages = ['*']
            options.name_legacy = True
            options.layout_features = ['*']
            options.notdef_outline = True
            worker = subset.Subsetter(options=options)
            worker.populate(unicodes=characters)
            worker.subset(font)
            font.flavor = 'woff2'
            filename = f'LXGWWenKaiMonoGB-{style}-{group}.woff2'
            font.save(output / filename)
            font.close()
            styles.append(f'''@font-face {{
  font-family: "LXGW WenKai Mono GB";
  font-style: normal;
  font-weight: {weight};
  font-display: swap;
  src: url("./{filename}") format("woff2");
  unicode-range: {unicode_ranges(characters)};
}}''')
            report['fonts'].append({'file': filename, 'weight': weight, 'group': group,
                                    'characters': len(characters), 'bytes': (output / filename).stat().st_size,
                                    'source_sha256': digest})
    shutil.copyfile(source / 'OFL.txt', output / 'OFL.txt')
    (output / 'font.css').write_text('\n\n'.join(styles) + '\n', encoding='utf-8')
    (output / 'SOURCE.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps(report, ensure_ascii=False))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, help='官方 Regular/Medium TTF 与 OFL.txt 所在目录')
    parser.add_argument('--output', type=Path,
                        default=Path(__file__).resolve().parents[1] / 'theme/fonts/lxgw-wenkai-mono-gb')
    args = parser.parse_args()
    prepare(args.source, args.output)
